import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const require = createRequire(resolve(process.env.PLAYWRIGHT_MODULE_ROOT || '.', 'package.json'))
const { chromium } = require('playwright')
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:4174'
const output = resolve('artifacts/experience-performance-qa/interactions')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE })
try {
  const catalog = await (await fetch(`${base}/api/works`)).json()
  const work = catalog.items.find(item => item.format === 'longform')
  const bootstrap = await (await fetch(`${base}/api/works/${work.id}/reader-bootstrap`)).json()
  for (const width of [320, 390, 768, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: width >= 700 ? 900 : 844 } })
    const errors = [], requests = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.url().includes('/api/')) requests.push(new URL(request.url()).pathname) })
    const go = path => page.goto(`${base}/preview/?page=${encodeURIComponent(path)}`)
    const screenshot = async name => {
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${name} overflow at ${width}`)
      await page.screenshot({ path: resolve(output, `${name}-${width}.png`) })
    }
    await go(`/pages/reader/index?workId=${work.id}&chapterId=${bootstrap.chapter.id}`)
    await page.locator('.long-chapter-title').waitFor()
    await page.waitForTimeout(250)
    assert.equal(requests.filter(path => path.endsWith('/reader-bootstrap')).length, 1)
    assert.equal(requests.some(path => path.endsWith('/assets') || path.endsWith('/chapters') || path === `/api/chapters/${bootstrap.chapter.id}`), false)
    await screenshot('reader')
    await page.locator('.reader-control').filter({ hasText: '下章' }).click()
    await page.waitForFunction(title => document.querySelector('.long-chapter-title')?.textContent === title, bootstrap.next.title)
    assert.equal(requests.filter(path => path === `/api/chapters/${bootstrap.next.id}`).length, 1, 'prefetch must be reused')
    await page.locator('.reader-control').filter({ hasText: '目录' }).click()
    await page.locator('.directory-list').waitFor()
    await screenshot('directory')
    await go('/pages/search/index')
    await page.locator('input').fill('纸月亮')
    await page.locator('.result-card').first().waitFor()
    assert.match(await page.locator('.search-results').innerText(), /纸月亮失窃案/)
    await screenshot('search')
    await page.locator('input').fill('不存在的作品xxxx')
    await page.getByText('没有找到相关作品', { exact: true }).waitFor()
    await go('/pages/home/index')
    await page.locator('.book-tile').first().waitFor()
    await page.getByRole('button', { name: '书架', exact: true }).click()
    await page.locator('.shelf-page').waitFor()
    await page.waitForFunction(() => !document.querySelector('.shelf-page').textContent.includes('正在载入'))
    assert.equal(await page.locator('.main-nav').count(), 1)
    await screenshot('shelf')
    await page.locator('.main-nav').getByRole('button', { name: '我的', exact: true }).click()
    await page.locator('.me-page').waitFor()
    assert.equal(await page.locator('.bottom-nav').count(), 0)
    assert.equal(await page.locator('.main-nav').count(), 1)
    await screenshot('me')
    await page.locator('.main-nav').getByRole('button', { name: '创作', exact: true }).click()
    await page.locator('.creator-page').waitFor()
    await page.getByRole('button', { name: '书城', exact: true }).click()
    await page.locator('.book-tile').first().waitFor()
    assert.deepEqual(errors, [])
    await page.close()
    console.log(`PASS ${width}px: aggregated reader, reused prefetch, directory, server search, empty result, four-section navigation`)
  }
  const weak = await browser.newPage({ viewport: { width: 390, height: 844 } })
  let releaseLogin
  const loginGate = new Promise(resolve => { releaseLogin = resolve })
  await weak.route('**/api/auth/dev-login', async route => { await loginGate; await route.continue() })
  await weak.goto(`${base}/preview/?page=${encodeURIComponent(`/pages/reader/index?workId=${work.id}&chapterId=${bootstrap.chapter.id}`)}`)
  await weak.locator('.long-chapter-title').waitFor({ timeout: 10000 })
  console.log('PASS public reading renders while login is still pending')
  releaseLogin(); await weak.close()
  const race = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await race.route('**/api/works?*', async route => {
    const q = new URL(route.request().url()).searchParams.get('q')
    if (q === '纸') await new Promise(resolve => setTimeout(resolve, 850))
    await route.continue()
  })
  await race.goto(`${base}/preview/?page=${encodeURIComponent('/pages/search/index')}`)
  await race.locator('input').fill('纸')
  await race.waitForRequest(request => new URL(request.url()).searchParams.get('q') === '纸')
  await race.locator('input').fill('寒门')
  await race.getByText('寒门掌兵', { exact: true }).waitFor()
  await race.waitForTimeout(1000)
  assert.equal(await race.locator('.result-card').count(), 1)
  assert.match(await race.locator('.search-results').innerText(), /寒门掌兵/)
  await race.locator('input').fill(''); await race.locator('.search-hints').waitFor()
  await race.close(); console.log('PASS slow old search response cannot replace current results')
} finally { await browser.close() }
