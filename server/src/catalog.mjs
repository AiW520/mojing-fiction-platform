export function catalogWordCount(book) {
  return book.chapters.reduce((total, chapter) => total + chapter.content.replace(/\s/g, '').length, 0)
}

export function catalogMeta(book) {
  return {
    coverImage: `/assets/books/editorial/${book.id.replace('work_', '')}.webp`,
    cover: book.cover,
    reads: book.reads,
    score: book.score,
    tagline: book.tagline,
    readMinutes: Math.max(1, Math.ceil(catalogWordCount(book) / 350)),
    chapterCount: book.chapters.length,
    characterCount: book.characters.length,
  }
}
